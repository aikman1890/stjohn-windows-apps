using System.Text;
using RallyPilot.Models;
using RallyPilot.Services;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Xaml.Navigation;
using Windows.Storage;
using Windows.Storage.Pickers;

namespace RallyPilot.Views;

public sealed partial class RosterPage : Page
{
    private readonly JsonListStore<RosterEntry> _store = new("roster.json");
    private readonly JsonListStore<RallyEvent> _eventStore = new("events.json");
    private List<RallyEvent> _events = new();

    public RosterPage()
    {
        this.InitializeComponent();
        SignedBox.ItemsSource = new[] { "Signed", "Unsigned" };
        EventBox.SelectionChanged += async (_, _) => await RefreshAsync();
    }

    protected override async void OnNavigatedTo(NavigationEventArgs e)
    {
        _events = (await _eventStore.LoadAsync()).OrderBy(ev => ev.EventDate).ToList();
        EventBox.ItemsSource = _events.Select(ev => $"{ev.EventDate:MMM d} - {ev.CompanyLabel}").ToList();
        if (_events.Count > 0) EventBox.SelectedIndex = 0;
        await RefreshAsync();
    }

    private RallyEvent? Current =>
        EventBox.SelectedIndex >= 0 && EventBox.SelectedIndex < _events.Count
            ? _events[EventBox.SelectedIndex] : null;

    private async Task<List<RosterEntry>> MineAsync()
    {
        if (Current is null) return new List<RosterEntry>();
        var all = await _store.LoadAsync();
        return all.Where(r => r.EventId == Current.Id).OrderBy(r => r.Name).ToList();
    }

    private async Task RefreshAsync()
    {
        var mine = await MineAsync();
        RosterList.ItemsSource = mine;
        var unsigned = mine.Where(r => !r.WaiverSigned).ToList();
        ChaseText.Text = Current is null ? string.Empty
            : mine.Count == 0 ? "No roster yet - add participants as the organizer sends them."
            : unsigned.Count == 0 ? $"ROSTER CLEAR: all {mine.Count} participant(s) signed."
            : $"CHASE {unsigned.Count} of {mine.Count}: {string.Join(", ", unsigned.Select(r => r.Name))}";
    }

    private async void AddButton_Click(object sender, RoutedEventArgs e)
    {
        if (Current is null) { ErrorText.Text = "Pick the event."; return; }
        if (string.IsNullOrWhiteSpace(NameBox.Text)) { ErrorText.Text = "Name the participant."; return; }
        var all = await _store.LoadAsync();
        var existing = all.FirstOrDefault(r => r.EventId == Current.Id &&
            r.Name.Equals(NameBox.Text.Trim(), StringComparison.OrdinalIgnoreCase));
        var signed = SignedBox.SelectedItem as string == "Signed";
        if (existing is not null)
        {
            existing.WaiverSigned = signed;
            existing.WaiverVersion = VersionBox.Text.Trim();
        }
        else
        {
            all.Add(new RosterEntry
            {
                EventId = Current.Id, EventLabel = $"{Current.CompanyLabel} {Current.EventDate:MMM d}",
                Name = NameBox.Text.Trim(), WaiverSigned = signed, WaiverVersion = VersionBox.Text.Trim(),
            });
        }
        await _store.SaveAsync(all);
        NameBox.Text = string.Empty;
        await RefreshAsync();
    }

    private async void ExportButton_Click(object sender, RoutedEventArgs e)
    {
        if (Current is null) { ErrorText.Text = "Pick the event."; return; }
        var mine = await MineAsync();
        var unsigned = mine.Where(r => !r.WaiverSigned).ToList();
        var sb = new StringBuilder();
        sb.AppendLine($"Waiver chase list - {Current.CompanyLabel} - event {Current.EventDate:dddd, MMM d, yyyy}");
        sb.AppendLine($"Organizer: {Current.OrganizerLabel} {Current.OrganizerContact}");
        sb.AppendLine(unsigned.Count == 0
            ? "All participants have signed. Nothing to chase."
            : $"The following {unsigned.Count} participant(s) still need a signed waiver before the event:");
        foreach (var r in unsigned) sb.AppendLine($"- {r.Name}");
        sb.AppendLine("Generated by RallyPilot from the event roster.");
        var picker = new FileSavePicker { SuggestedStartLocation = PickerLocationId.DocumentsLibrary };
        picker.FileTypeChoices.Add("Text file", new List<string> { ".txt" });
        picker.SuggestedFileName = "waiver-chase-list.txt";
        if (App.WindowInstance is not null)
            WinRT.Interop.InitializeWithWindow.Initialize(picker, WinRT.Interop.WindowNative.GetWindowHandle(App.WindowInstance));
        var file = await picker.PickSaveFileAsync();
        if (file is null) return;
        await FileIO.WriteTextAsync(file, sb.ToString());
        StatusText.Text = $"Chase list saved to {file.Path}";
    }
}
