using System.Net;
using System.Text;
using RallyPilot.Models;
using RallyPilot.Services;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Xaml.Navigation;
using Windows.Storage;
using Windows.Storage.Pickers;

namespace RallyPilot.Views;

public sealed partial class ReportsPage : Page
{
    private readonly JsonListStore<RallyEvent> _eventStore = new("events.json");
    private List<RallyEvent> _events = new();

    public ReportsPage()
    {
        this.InitializeComponent();
    }

    protected override async void OnNavigatedTo(NavigationEventArgs e)
    {
        _events = (await _eventStore.LoadAsync()).OrderBy(ev => ev.EventDate).ToList();
        EventBox.ItemsSource = _events.Select(ev => $"{ev.EventDate:MMM d} - {ev.CompanyLabel}").ToList();
        if (_events.Count > 0) EventBox.SelectedIndex = 0;
    }

    private static string Esc(string s) => WebUtility.HtmlEncode(s ?? string.Empty);

    private async void ExportButton_Click(object sender, RoutedEventArgs e)
    {
        if (EventBox.SelectedIndex < 0 || EventBox.SelectedIndex >= _events.Count) return;
        var ev = _events[EventBox.SelectedIndex];
        var settings = await new RallySettingsStore().LoadAsync();
        var sales = await new JsonListStore<AddOnSale>("addonsales.json").LoadAsync();
        var mine = sales.Where(s => s.EventId == ev.Id).OrderBy(s => s.Date).ToList();
        var roster = await new JsonListStore<RosterEntry>("roster.json").LoadAsync();
        var party = roster.Where(r => r.EventId == ev.Id).ToList();
        var final = ev.QuotedTotal + mine.Sum(s => s.LineTotal);
        var collected = ev.DepositPaid + ev.PaymentsReceived;
        var balance = final - collected;
        var perHead = ev.ConfirmedHeads > 0 ? final / ev.ConfirmedHeads : 0m;

        var sb = new StringBuilder();
        sb.AppendLine("<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>Event close</title>");
        sb.AppendLine("<style>body{font-family:Segoe UI,Arial,sans-serif;margin:40px;color:#222}h1{font-size:21px}h2{font-size:15px;margin-top:18px}li{margin:3px 0}.tot{font-weight:600;font-size:16px}</style></head><body>");
        sb.AppendLine($"<h1>{Esc(settings.BusinessName)} - Event close: {Esc(ev.CompanyLabel)}</h1>");
        sb.AppendLine($"<p>{ev.EventDate:dddd, MMM d, yyyy} - organizer {Esc(ev.OrganizerLabel)} {Esc(ev.OrganizerContact)} - {Esc(ev.QuoteRef)}</p>");
        sb.AppendLine($"<p>Heads: {ev.ConfirmedHeads} confirmed of {ev.ExpectedHeads} expected - roster {party.Count}, waivers signed {party.Count(r => r.WaiverSigned)}.</p>");
        sb.AppendLine("<h2>Money</h2><ul>");
        sb.AppendLine($"<li>Quoted total: {ev.QuotedTotal:0.00} {Esc(ev.Currency)}</li>");
        foreach (var s in mine) sb.AppendLine($"<li>Add-on: {Esc(s.Label)} - {s.Qty:0.##} x {s.UnitPrice:0.00} = {s.LineTotal:0.00}</li>");
        sb.AppendLine($"<li>Final total: {final:0.00}</li>");
        sb.AppendLine($"<li>Collected (deposit {ev.DepositPaid:0.00} + payments {ev.PaymentsReceived:0.00}): {collected:0.00}</li>");
        sb.AppendLine($"<li>Balance: {balance:0.00}</li>");
        sb.AppendLine($"<li>Per-head realized revenue: {perHead:0.00}</li>");
        sb.AppendLine("</ul><h2>Follow-up</h2><ul>");
        sb.AppendLine($"<li>Thank-you sent: {(ev.ThankYouSent ? "yes" : "no")}</li>");
        sb.AppendLine($"<li>Rebook prompt: {(ev.RebookPromptDate is { } r ? r.ToString("MMM d, yyyy") : "not set")}</li>");
        sb.AppendLine("</ul><p>Generated by RallyPilot from the operator's local event book.</p></body></html>");

        PreviewText.Text = $"{ev.CompanyLabel}: final {final:0.00}, collected {collected:0.00}, balance {balance:0.00}, per-head {perHead:0.00}.";
        var picker = new FileSavePicker { SuggestedStartLocation = PickerLocationId.DocumentsLibrary };
        picker.FileTypeChoices.Add("HTML document", new List<string> { ".html" });
        picker.SuggestedFileName = "event-close.html";
        if (App.WindowInstance is not null)
            WinRT.Interop.InitializeWithWindow.Initialize(picker, WinRT.Interop.WindowNative.GetWindowHandle(App.WindowInstance));
        var file = await picker.PickSaveFileAsync();
        if (file is null) return;
        await FileIO.WriteTextAsync(file, sb.ToString());
        StatusText.Text = $"Close report saved to {file.Path}";
    }
}
