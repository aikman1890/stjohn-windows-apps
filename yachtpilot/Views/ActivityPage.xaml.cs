using System.Net;
using System.Text;
using YachtPilot.Models;
using YachtPilot.Services;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Xaml.Navigation;
using Windows.Storage;
using Windows.Storage.Pickers;

namespace YachtPilot.Views;

public sealed partial class ActivityPage : Page
{
    private readonly JsonListStore<ActivityEntry> _store = new("activity.json");
    private readonly JsonListStore<Vessel> _vesselStore = new("vessels.json");
    private List<ActivityEntry> _all = new();
    private List<Vessel> _vessels = new();

    public ActivityPage()
    {
        this.InitializeComponent();
        KindBox.ItemsSource = new[] { "Certificate renewed", "Service completed", "Charter run", "Statement sent", "Other" };
        VesselBox.SelectionChanged += (_, _) => RefreshList();
    }

    protected override async void OnNavigatedTo(NavigationEventArgs e)
    {
        _vessels = (await _vesselStore.LoadAsync()).OrderBy(v => v.Name).ToList();
        VesselBox.ItemsSource = new[] { "(all vessels)" }.Concat(_vessels.Select(v => v.Name)).ToList();
        VesselBox.SelectedIndex = 0;
        _all = (await _store.LoadAsync()).OrderByDescending(a => a.Date).ToList();
        RefreshList();
    }

    private void RefreshList()
    {
        var idx = VesselBox.SelectedIndex;
        ActivityList.ItemsSource = idx <= 0
            ? _all
            : _all.Where(a => a.VesselId == _vessels[idx - 1].Id).ToList();
    }

    private async void AddButton_Click(object sender, RoutedEventArgs e)
    {
        var idx = VesselBox.SelectedIndex;
        if (idx <= 0) { StatusText.Text = "Pick a specific vessel to add an entry."; return; }
        var v = _vessels[idx - 1];
        _all.Insert(0, new ActivityEntry
        {
            VesselId = v.Id, VesselLabel = v.Name,
            Kind = KindBox.SelectedItem as string ?? "Other",
            Detail = DetailBox.Text.Trim(), MethodNote = MethodBox.Text.Trim(),
            Date = DateTimeOffset.Now,
        });
        await _store.SaveAsync(_all);
        DetailBox.Text = MethodBox.Text = string.Empty;
        RefreshList();
    }

    private static string Esc(string s) => WebUtility.HtmlEncode(s ?? string.Empty);

    private async void ExportButton_Click(object sender, RoutedEventArgs e)
    {
        var idx = VesselBox.SelectedIndex;
        var rows = (idx <= 0 ? _all : _all.Where(a => a.VesselId == _vessels[idx - 1].Id))
            .OrderBy(a => a.Date).ToList();
        var label = idx <= 0 ? "All vessels" : _vessels[idx - 1].Name;
        var sb = new StringBuilder();
        sb.AppendLine("<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>Activity ledger</title>");
        sb.AppendLine("<style>body{font-family:Segoe UI,Arial,sans-serif;margin:40px;color:#222}h1{font-size:20px}li{margin:4px 0}</style></head><body>");
        sb.AppendLine($"<h1>Activity ledger - {Esc(label)}</h1><ul>");
        foreach (var a in rows)
            sb.AppendLine($"<li>{a.Date:MMM d, yyyy} - {Esc(a.Kind)} - {Esc(a.Detail)} ({Esc(a.MethodNote)})</li>");
        sb.AppendLine("</ul><p>Generated by YachtPilot from the manager's local proof ledger.</p></body></html>");
        var picker = new FileSavePicker { SuggestedStartLocation = PickerLocationId.DocumentsLibrary };
        picker.FileTypeChoices.Add("HTML document", new List<string> { ".html" });
        picker.SuggestedFileName = "activity-ledger.html";
        if (App.WindowInstance is not null)
            WinRT.Interop.InitializeWithWindow.Initialize(picker, WinRT.Interop.WindowNative.GetWindowHandle(App.WindowInstance));
        var file = await picker.PickSaveFileAsync();
        if (file is null) return;
        await FileIO.WriteTextAsync(file, sb.ToString());
        StatusText.Text = $"Ledger saved to {file.Path}";
    }
}
