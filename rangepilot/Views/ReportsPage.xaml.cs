using System.Net;
using System.Text;
using RangePilot.Models;
using RangePilot.Services;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Xaml.Navigation;
using Windows.Storage;
using Windows.Storage.Pickers;

namespace RangePilot.Views;

public sealed partial class ReportsPage : Page
{
    public ReportsPage()
    {
        this.InitializeComponent();
        DayPicker.Date = DateTimeOffset.Now;
    }

    protected override void OnNavigatedTo(NavigationEventArgs e) { }

    private static string Esc(string s) => WebUtility.HtmlEncode(s ?? string.Empty);

    private async void ExportButton_Click(object sender, RoutedEventArgs e)
    {
        var day = (DayPicker.Date ?? DateTimeOffset.Now).Date;
        var settings = await new RangeSettingsStore().LoadAsync();
        var bookings = await new JsonListStore<Booking>("bookings.json").LoadAsync();
        var media = await new JsonListStore<MediaItem>("media.json").LoadAsync();
        var assets = await new JsonListStore<AssetItem>("assets.json").LoadAsync();
        var log = await new JsonListStore<AssetLogEntry>("assetlog.json").LoadAsync();
        var days = bookings.Where(b => b.SlotDate.Date == day && b.Status != "Cancelled").ToList();
        var revenue = days.Sum(b => b.TotalPrice);
        var balances = days.Sum(b => b.BalanceDue);
        var owed = media.Where(m => !m.Delivered).ToList();
        var downToday = log.Where(l => l.Date.Date == day).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>Day-close</title>");
        sb.AppendLine("<style>body{font-family:Segoe UI,Arial,sans-serif;margin:40px;color:#222}h1{font-size:21px}h2{font-size:15px;margin-top:18px}li{margin:3px 0}.tot{font-weight:600}</style></head><body>");
        sb.AppendLine($"<h1>{Esc(settings.BusinessName)} - Day-close, {day:dddd, MMM d, yyyy}</h1>");
        sb.AppendLine($"<p class=\"tot\">Bookings: {days.Count} - booked revenue {revenue:0.00} - balances still due {balances:0.00}</p>");
        sb.AppendLine("<h2>Revenue by package</h2><ul>");
        foreach (var g in days.GroupBy(b => b.PackageLabel))
            sb.AppendLine($"<li>{Esc(g.Key)}: {g.Count()} booking(s), {g.Sum(b => b.TotalPrice):0.00}</li>");
        sb.AppendLine("</ul><h2>Revenue by source (discount leakage, in dollars)</h2><ul>");
        foreach (var g in days.GroupBy(b => b.Source))
            sb.AppendLine($"<li>{Esc(g.Key)}: {g.Count()} booking(s), {g.Sum(b => b.TotalPrice):0.00}</li>");
        sb.AppendLine("</ul><h2>Media outstanding</h2><ul>");
        if (owed.Count == 0) sb.AppendLine("<li>None - everything delivered.</li>");
        foreach (var m in owed) sb.AppendLine($"<li>{Esc(m.DisplayLine)}</li>");
        sb.AppendLine("</ul><h2>Assets</h2><ul>");
        foreach (var a in assets) sb.AppendLine($"<li>{Esc(a.Name)}: {Esc(a.Status)}</li>");
        foreach (var l in downToday) sb.AppendLine($"<li>{Esc(l.AssetLabel)} - {Esc(l.Kind)}: {Esc(l.Detail)}</li>");
        sb.AppendLine("</ul><p>Generated by RangePilot from the operator's local book. Records tool, not compliance advice.</p></body></html>");

        PreviewText.Text = $"{day:MMM d}: {days.Count} booking(s), revenue {revenue:0.00}, balances {balances:0.00}, media owed {owed.Count}.";
        var picker = new FileSavePicker { SuggestedStartLocation = PickerLocationId.DocumentsLibrary };
        picker.FileTypeChoices.Add("HTML document", new List<string> { ".html" });
        picker.SuggestedFileName = $"day-close-{day:yyyy-MM-dd}.html";
        if (App.WindowInstance is not null)
            WinRT.Interop.InitializeWithWindow.Initialize(picker, WinRT.Interop.WindowNative.GetWindowHandle(App.WindowInstance));
        var file = await picker.PickSaveFileAsync();
        if (file is null) return;
        await FileIO.WriteTextAsync(file, sb.ToString());
        StatusText.Text = $"Day-close saved to {file.Path}";
    }
}
