using System.Globalization;
using System.Net;
using System.Text;
using HuntPilot.Models;
using HuntPilot.Services;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Xaml.Navigation;
using Windows.Storage;
using Windows.Storage.Pickers;

namespace HuntPilot.Views;

public sealed partial class ReportsPage : Page
{
    public ReportsPage()
    {
        this.InitializeComponent();
        YearBox.Text = DateTimeOffset.Now.Year.ToString(CultureInfo.InvariantCulture);
    }

    protected override void OnNavigatedTo(NavigationEventArgs e) { }

    private static string Esc(string s) => WebUtility.HtmlEncode(s ?? string.Empty);

    private async void ExportButton_Click(object sender, RoutedEventArgs e)
    {
        var year = int.TryParse(YearBox.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var y) ? y : DateTimeOffset.Now.Year;
        var settings = await new HuntSettingsStore().LoadAsync();
        var hunts = await new JsonListStore<HuntBooking>("hunts.json").LoadAsync();
        var harvests = await new JsonListStore<Harvest>("harvests.json").LoadAsync();
        var trophies = await new JsonListStore<TrophyCase>("trophies.json").LoadAsync();
        var season = hunts.Where(h => h.StartDate.Year == year && h.Status != "Cancelled").ToList();
        var seasonHarvests = harvests.Where(h => h.Date.Year == year).ToList();
        var revenue = season.Sum(h => h.TotalCharges);
        var balances = season.Where(h => h.BalanceDue > 0).ToList();
        var open = trophies.Where(t => !t.Closed).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>Season report</title>");
        sb.AppendLine("<style>body{font-family:Segoe UI,Arial,sans-serif;margin:40px;color:#222}h1{font-size:21px}h2{font-size:15px;margin-top:18px}li{margin:3px 0}.tot{font-weight:600}</style></head><body>");
        sb.AppendLine($"<h1>{Esc(settings.RanchName)} - Season report {year}</h1>");
        sb.AppendLine($"<p class=\"tot\">{season.Count} hunt(s) - booked revenue {revenue:0.00} - balances outstanding {balances.Sum(h => h.BalanceDue):0.00} across {balances.Count} hunt(s)</p>");
        sb.AppendLine("<h2>Harvests by species</h2><ul>");
        foreach (var g in seasonHarvests.GroupBy(h => h.SpeciesLabel))
            sb.AppendLine($"<li>{Esc(g.Key)}: {g.Count()} - trophy fees {g.Sum(h => h.TrophyFee):0.00}</li>");
        if (seasonHarvests.Count == 0) sb.AppendLine("<li>No harvests logged this season.</li>");
        sb.AppendLine("</ul><h2>Balances outstanding</h2><ul>");
        foreach (var h in balances) sb.AppendLine($"<li>{Esc(h.HunterLabel)} - {h.BalanceDue:0.00} {Esc(h.Currency)} (hunt {h.StartDate:MMM d})</li>");
        if (balances.Count == 0) sb.AppendLine("<li>None - every balance collected.</li>");
        sb.AppendLine("</ul><h2>Trophies outstanding by stage</h2><ul>");
        foreach (var g in open.GroupBy(t => t.Stage))
            sb.AppendLine($"<li>{Esc(g.Key)}: {g.Count()} - longest {g.Max(t => t.DaysInStage)} days</li>");
        if (open.Count == 0) sb.AppendLine("<li>None - every trophy delivered.</li>");
        sb.AppendLine("</ul><h2>Repeat-marketing list (this season's hunters)</h2><ul>");
        foreach (var name in season.Select(h => h.HunterLabel).Distinct()) sb.AppendLine($"<li>{Esc(name)}</li>");
        sb.AppendLine("</ul><p>Generated by HuntPilot from the ranch's local book. Records tool, not legal or compliance advice.</p></body></html>");

        PreviewText.Text = $"{year}: {season.Count} hunt(s), revenue {revenue:0.00}, balances {balances.Sum(h => h.BalanceDue):0.00}, trophies open {open.Count}.";
        var picker = new FileSavePicker { SuggestedStartLocation = PickerLocationId.DocumentsLibrary };
        picker.FileTypeChoices.Add("HTML document", new List<string> { ".html" });
        picker.SuggestedFileName = $"season-report-{year}.html";
        if (App.WindowInstance is not null)
            WinRT.Interop.InitializeWithWindow.Initialize(picker, WinRT.Interop.WindowNative.GetWindowHandle(App.WindowInstance));
        var file = await picker.PickSaveFileAsync();
        if (file is null) return;
        await FileIO.WriteTextAsync(file, sb.ToString());
        StatusText.Text = $"Season report saved to {file.Path}";
    }
}
